using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace StickAndPuck.Analyzers;

/// <summary>Registers scenes and modes at compile time, preserving automatic discovery under trimming.</summary>
[Generator]
public sealed class DiscoveryGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax { BaseList: { } },
            static (syntax, token) => syntax.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)syntax.Node, token) as INamedTypeSymbol)
            .Where(static type => type is { IsAbstract: false, TypeKind: TypeKind.Class } && type.TypeParameters.Length == 0
                && type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal))
            .Collect();
        context.RegisterSourceOutput(types, static (output, found) => Emit(output, found));
    }

    static void Emit(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> types)
    {
        const string Scene = "StickAndPuck.App.Core.IScene", Mode = "StickAndPuck.App.Screens.IGameMode";
        string[] Names(string contract) => types.Where(type => type.AllInterfaces.Any(i => string.Equals(i.ToDisplayString(), contract, StringComparison.Ordinal)))
            .Select(type => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Distinct(StringComparer.Ordinal).OrderBy(name => name, StringComparer.Ordinal).ToArray();
        string[] scenes = Names(Scene), modes = Names(Mode);
        if (scenes.Length == 0 && modes.Length == 0) return;
        var source = new StringBuilder("// <auto-generated/>\nnamespace StickAndPuck.App.Core;\ninternal static class DiscoveryRegistry\n{\n");
        Append("Scenes", Scene, scenes);
        Append("Modes", Mode, modes);
        source.Append("}\n");
        context.AddSource("DiscoveryRegistry.g.cs", source.ToString());

        void Append(string method, string contract, string[] names)
        {
            source.Append("    internal static global::").Append(contract).Append("[] ").Append(method).Append("() => new global::").Append(contract).Append("[] {\n");
            foreach (string name in names) source.Append("        new ").Append(name).Append("(),\n");
            source.Append("    };\n");
        }
    }
}

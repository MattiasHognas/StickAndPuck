# Å: the ring's lower half is the A's apex, so the A starts one row lower and loses its top row.
_ACCENT["Å"] = ("A", ["..#..", ".#.#."], ["..#..", ".#.#.", "#...#", "#####", "#...#", "#...#", "#...#"])

_DESC = {
    ",": ([".", ".", ".", ".", ".", ".", "#"], ["#", "."]),
    ";": ([".", ".", "#", ".", ".", ".", "#"], ["#", "."]),
    "_": (["....."] * 7, ["#####", "....."]),
}

HEIGHT = 11       # rows per glyph
BASE = 9          # baseline: rows 0..8 sit above it


def glyphs():
    """Return {char: list of HEIGHT strings}."""
    out = {}
    for ch, rows in _CAP.items():
        w = len(rows[0])
        out[ch] = ["." * w] * 2 + rows + ["." * w] * 2
    for ch, (base, top, body) in _ACCENT.items():
        rows = body or _CAP[base]
        out[ch] = top + rows + ["." * len(rows[0])] * 2
    for ch, (base, top, body, below) in _NAMES.items():
        rows = body or _CAP[base]
        out[ch] = top + rows + (below or ["." * len(rows[0])] * 2)
    for ch, (rows, low) in _DESC.items():
        w = len(rows[0])
        out[ch] = ["." * w] * 2 + rows + low
    for ch, rows in out.items():
        assert len(rows) == HEIGHT and len({len(r) for r in rows}) == 1, ch
    return out

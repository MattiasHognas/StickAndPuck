namespace StickAndPuck.App.Season.News
{
    /// <summary>What a news card does to the human's club.</summary>
    public enum NewsEffect
    {
        /// <summary>Trait points on some skaters for some games (flu, a rookie call-up, a contract dispute).</summary>
        Traits,

        /// <summary>The club starts its next games tired (a travel delay).</summary>
        Energy,

        /// <summary>A team morale nudge when the card is drawn (a fan night).</summary>
        Morale,
    }
}
